"""Single-target managed placement acceptance with a checkpointed interruption.

Uses the established mesh and Qwen TP2 capture; every candidate is generated by
the library from the entire snapshot. Extra allocations obey the input budget
throughout replacement. One real restore per layout, no automatic repetitions.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import resource
import time

from run_placement_comparison import PlacementRun
from fluidckpt.cluster.managed_control import ManagedPlacementError
from fluidckpt.serving.measure import summarize
from fluidckpt.topology.placement import choose_numa_owners


class ManagedRun(PlacementRun):
    def __init__(self, args):
        self.config = json.loads(args.config.read_text())
        args.model = self.config["model"]
        super().__init__(args)
        self.placement = None
        self.result["input_config"] = self.config
        self.result["input_config_sha256"] = hashlib.sha256(args.config.read_bytes()).hexdigest()

    def preflight(self):
        super().preflight()
        requirements = []
        for worker, (node, gpu) in enumerate(self.members):
            n = self.config["base_dram_bytes_per_rank"] if worker in (0, 1, 4, 5) else 0
            n += sum(loc["max_bytes"]+loc.get("temporary_bytes", 0)
                     for loc in self.config["budget"]["locations"]
                     if loc["worker"] == worker and loc["tier"] == "dram")
            requirements.append({"node": node, "gpu": gpu, "nbytes": n})
        placement = choose_numa_owners(self.probes, requirements)
        self.args.worker_numa = placement["owners"]
        self.result["numa_preflight"] = placement
        self.event("numa_capacity_checked", owners=placement["owners"])

    def fixture(self):
        self.event("acceptance_scope", samples_per_layout=1,
            expected_bytes=70329718112, expected_generation_checks=3,
            expected_tier_peak_bytes=self.config["budget"]["tier_bytes"],
            expected_checkpoint_retry="same plan resumes without rebuilding committed replicas",
            expected_candidates="whole model including exact tails; per-target 8GiB HBM allowed")

    def restore_model(self, node, phase, sources, dsts, strategy, source_ids, reference):
        # Match the previous path's process, layout, transfer and verification boundaries.
        server = self.server(node, phase, "restore")
        self.wait_exports(phase)
        targets = [dict(self.replica_target(s, f"{phase}/{g}", dsts[g]), mode="live", tag=phase,
                        metrics_directory=str(self.out/"metrics"/phase)) for g, s in enumerate(sources)]
        started = time.monotonic()
        plan = (self.cluster.plan_managed_restore(self.placement, targets) if self.placement else
                self.cluster.plan_restore(targets, "resource_lp", source_ids))
        planned = time.monotonic()
        if plan["strategy"] != "resource_lp" or plan["fallback_reason"]:
            raise AssertionError("restore LP fallback")
        flow = self.cluster.transfer(plan, verify_before_ready=False, retain=True)
        self.event("weights_transferred", phase=phase, source_bytes=flow["source_bytes"])
        replies = self.generate(node)
        if [r["text"] for r in replies] != [r["text"] for r in reference]:
            raise AssertionError("restored generation differs from capture")
        verification = self.cluster.verify(flow["tx"])
        timing = summarize(self.out/"metrics"/phase, 2)
        self.cluster.finish(flow["tx"]); self.stop(server)
        self.result["restores"].append({"phase": phase, "node": node, "strategy": "resource_lp",
            "flow": flow, "verification": verification, "timing": timing,
            "replies": replies, "passed": True, "plan_wall_s": planned-started})
        self.event("model_restore_passed", phase=phase, load_s=timing["load_s"],
                   verified_bytes=verification["checked_bytes"])

    def real_model(self):
        sources, reference = self.prepare_model()
        self.calibrate(sources)
        self.result["scope"] = ("single Qwen TP2 destination node29; immutable node28 DRAM base; "
            "full-model candidates; up to 8GiB HBM + 2GiB DRAM; per-GPU HBM up to 8GiB; "
            "zero temporary allowance; one observed restore per layout")
        workers, replicas = self.cluster.inventory(compact=True)
        future = [self.replica_target(s, f"future/{g}", g+6) for g, s in enumerate(sources)]
        q = {"schema_version": 1, "scope": self.args.run, "executor": "serial", "targets": future,
             "base_ids": [f"model/remote/{g}" for g in range(2)],
             "managed_ids": sorted(r["id"] for r in replicas if not r["id"].startswith("model/remote/")),
             **{k: copy.deepcopy(self.config[k]) for k in
                ("budget", "block_bytes", "minimum_gain_s", "max_candidates")}}
        self.result["layouts"] = {"existing": self.layout()}
        # Warm the same planning endpoint for both layouts before the live load timer.
        self.cluster.plan_restore(future, "resource_lp")
        self.restore_model("node29", "managed_existing", sources, [6, 7], "resource_lp", None, reference)
        stamp = time.monotonic()
        plan = self.cluster.plan_joint(q)
        self.result["joint_plan_wall_s"] = time.monotonic()-stamp
        self.result["joint_plan"] = plan
        (self.out/"placement_plan.json").write_text(json.dumps(plan, indent=2))
        if plan["fallback_reason"]: raise AssertionError("joint solver fallback: "+plan["fallback_reason"])
        if not plan["transition"]["actions"]: raise AssertionError("test did not exercise layout replacement")
        self.event("joint_plan_ready", decision=plan["decision"], candidates=plan["candidates"]["count"],
                   solver=plan["solver"]["status"], before_s=plan["predicted_before_s"], after_s=plan["predicted_after_s"])
        journal_path = self.out/"placement_journal.json"
        stamp = time.monotonic()
        try:
            self.cluster.apply_joint(plan, journal_path=journal_path, fail_after_actions=1)
        except ManagedPlacementError as exc:
            if "injected interruption" not in str(exc): raise
            self.result["interrupted_journal"] = exc.journal
            self.event("checkpoint_interruption_verified", completed=exc.journal["next_action"])
        else:
            raise AssertionError("injected interruption did not fire")
        journal = self.cluster.apply_joint(plan, journal_path=journal_path)
        self.result["transition"] = {"wall_s": time.monotonic()-stamp, "journal": journal}
        if self.cluster.apply_joint(plan, journal_path=journal_path) != journal:
            raise AssertionError("applied plan replay changed journal")
        self.placement = plan
        self.result["layouts"]["managed"] = self.layout()
        self.cluster.plan_managed_restore(plan, future)
        self.event("managed_layout_ready", selected=len(plan["selected"]), usage=journal["final_usage"])
        self.restore_model("node29", "managed_optimized", sources, [6, 7], "resource_lp", None, reference)
        self.result["stages"]["managed_single_target"] = {"passed": True,
            "checkpoint_retry": True, "idempotent_replay": True, "samples": 2}


if __name__ == "__main__":
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True)
    parser.add_argument("--config", type=Path, default=Path("codex_coding/src/task2/configs/managed_single_target.json"))
    parser.add_argument("--port-base", type=int, default=25100)
    parser.set_defaults(worker_serialize=0, handoff_poll=.01, fixture_only=False)
    ManagedRun(parser.parse_args()).run()
